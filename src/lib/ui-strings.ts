export type UiStringId = keyof typeof en;
type Table = Partial<Record<UiStringId, string>>;

/** Built-in tables by BCP 47 tag or primary subtag; add one here to ship a translation. */
const TABLES: Record<string, Table> = { en };

/** `t(id, vars)` for the site's language: config `ui` overrides, then the language's table, then English. */
export function uiStrings(config: { lang?: string; ui?: Record<string, unknown> }) {
  const lang = (config.lang ?? 'en').toLowerCase();
  const overrides = Object.fromEntries(
    Object.entries(config.ui ?? {}).filter(([id, v]) => id in en && typeof v === 'string'),
  ) as Table;
  const table: Record<UiStringId, string> = { ...en, ...TABLES[lang.split('-')[0]], ...TABLES[lang], ...overrides };
  return (id: UiStringId, vars: Record<string, string | number> = {}) =>
    table[id].replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

export type Translate = ReturnType<typeof uiStrings>;
